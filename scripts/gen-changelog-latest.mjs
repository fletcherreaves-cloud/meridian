#!/usr/bin/env node
// ── Generate changelog-latest.js from the highest version under src/app/changelog/ ──
// R6 (dispatch16, 2026-08-17). Before this, changelog-latest.js and changelog-data.js's newest
// entry were two hand-maintained literals kept in sync by convention + a test that only caught
// drift AFTER it shipped. Splitting into one file per version (src/app/changelog/<version>.js)
// removes the shared-tail-of-array contention that caused five sequential PR rebases in one
// morning — but it also means there is no longer one array to eyeball for "what's newest". This
// script IS the sync mechanism now: it derives LATEST_CHANGELOG_ENTRY from the real files instead
// of asking a human (or an agent) to hand-copy the newest entry into a second location.
//
// Deliberately drops `changes` — App.js only ever reads .version and .date from
// LATEST_CHANGELOG_ENTRY (see App.js's MERIDIAN_VERSION/MERIDIAN_BUILD_DATE derivation). Shipping
// the newest entry's full prose here was #234: dead weight in the entry chunk every version file
// already carries once, correctly, for the lazy changelog panel.
//
// Usage:  node scripts/gen-changelog-latest.mjs [--write]
//         --write updates src/app/changelog-latest.js in place. Without it, prints what would be
//         written and exits non-zero if that differs from the committed file (staleness check —
//         same shape as gen-loader-emits.mjs's EMITS block, run in CI via
//         src/__tests__/ratchet-changelog-latest.test.js so a forgotten regen fails the suite,
//         not just a human's memory).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const DIR = 'src/app/changelog';
const OUT = 'src/app/changelog-latest.js';

const files = readdirSync(DIR).filter(f => /^\d[\w.]*\.js$/.test(f) && f !== 'index.js');

let best = null;
for (const f of files) {
  const src = readFileSync(`${DIR}/${f}`, 'utf8');
  const m = src.match(/export default \{version:'([^']+)', date:'(\d{4}-\d{2}-\d{2})'/);
  if (!m) { console.error(`[gen-changelog-latest] ${f}: could not parse version/date, skipping`); continue; }
  const [, version, date] = m;
  // Same Major.Minor numeric comparator changelog-panel.js's versionSort and the old
  // changelog-version.test.js used — a non-numeric segment (the historical '4.18x' entry)
  // compares as NaN, which is never > anything, so it can never win this race.
  const [maj, min] = version.split('.').map(Number);
  if (!best || maj > best.maj || (maj === best.maj && min > best.min)) {
    best = { version, date, maj, min, file: f };
  }
}

if (!best) { console.error('[gen-changelog-latest] no version files found'); process.exit(1); }

const content = `// @ts-nocheck
// #230 — the ONE changelog entry App.js needs synchronously: the latest version+date, for the
// footer text ('Meridian. v'+MERIDIAN_VERSION) and window.__MERIDIAN_VERSION__. Deliberately
// standalone — does NOT import from src/app/changelog/, and is not imported by it — so App.js's
// static import of this file stays tiny regardless of how large the full changelog grows.
//
// GENERATED by scripts/gen-changelog-latest.mjs — do not hand-edit. Run
// \`node scripts/gen-changelog-latest.mjs --write\` after adding a new src/app/changelog/<version>.js
// file; src/__tests__/ratchet-changelog-latest.test.js fails the suite if this drifts from the
// real max version, so a forgotten regen is caught before it ships, not after (R6, dispatch16).
export const LATEST_CHANGELOG_ENTRY = {version:'${best.version}', date:'${best.date}'};
`;

if (process.argv.includes('--write')) {
  writeFileSync(OUT, content);
  console.log(`[gen-changelog-latest] wrote ${OUT}: v${best.version} (${best.date}, from ${best.file})`);
} else {
  const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return null; } })();
  if (current !== content) {
    console.error(`[gen-changelog-latest] STALE: committed ${OUT} does not match derived v${best.version} (${best.date}). Run with --write.`);
    process.exit(1);
  }
  console.log(`[gen-changelog-latest] up to date: v${best.version} (${best.date})`);
}
